/**
 * Deterministic schema → TypeScript generator for @skillos/protocol.
 * Source of truth: packages/protocol/schemas/*.json
 * Output: packages/protocol/src/types.generated.ts
 *
 * Run: npx tsx scripts/generate-types.ts
 * Drift: npx tsx scripts/check-types-drift.ts
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const schemasDir = join(root, "schemas");
const outFile = join(root, "src", "types.generated.ts");

type JsonSchema = {
  title?: string;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  required?: string[];
  properties?: Record<string, JsonSchema>;
  additionalProperties?: boolean | JsonSchema;
  items?: JsonSchema;
  oneOf?: JsonSchema[];
  minLength?: number;
  pattern?: string;
  format?: string;
  minItems?: number;
  description?: string;
};

function loadSchemas(): { name: string; schema: JsonSchema; raw: string }[] {
  return readdirSync(schemasDir)
    .filter((f) => f.endsWith(".schema.json"))
    .sort()
    .map((f) => {
      const raw = readFileSync(join(schemasDir, f), "utf8");
      return { name: f, schema: JSON.parse(raw) as JsonSchema, raw };
    });
}

function tsTypeFromSchema(s: JsonSchema, indent = 0): string {
  if (s.const !== undefined) {
    return JSON.stringify(s.const);
  }
  if (s.enum) {
    return s.enum.map((e) => JSON.stringify(e)).join(" | ");
  }
  if (s.oneOf) {
    return s.oneOf.map((x) => tsTypeFromSchema(x, indent)).join(" | ");
  }
  const t = s.type;
  if (t === "string") return "string";
  if (t === "number" || t === "integer") return "number";
  if (t === "boolean") return "boolean";
  if (t === "null") return "null";
  if (t === "array") {
    const item = s.items ? tsTypeFromSchema(s.items, indent) : "unknown";
    // Parenthesize unions so `"a" | "b"[]` is not emitted.
    const needsParen = item.includes("|");
    return needsParen ? `(${item})[]` : `${item}[]`;
  }
  if (t === "object" || s.properties) {
    return objectType(s, indent);
  }
  if (Array.isArray(t)) {
    return t.map((x) => (x === "null" ? "null" : x)).join(" | ");
  }
  return "unknown";
}

function objectType(s: JsonSchema, indent: number): string {
  const props = s.properties ?? {};
  const required = new Set(s.required ?? []);
  const pad = "  ".repeat(indent + 1);
  const close = "  ".repeat(indent);
  const lines: string[] = ["{"];
  for (const key of Object.keys(props).sort()) {
    const prop = props[key]!;
    const opt = required.has(key) ? "" : "?";
    const doc = prop.description
      ? `${pad}/** ${prop.description.replace(/\*\//g, "*\\/")} */\n`
      : "";
    lines.push(
      `${doc}${pad}${JSON.stringify(key).slice(1, -1)}${opt}: ${tsTypeFromSchema(prop, indent + 1)};`,
    );
  }
  if (s.additionalProperties && typeof s.additionalProperties === "object") {
    lines.push(
      `${pad}[key: string]: ${tsTypeFromSchema(s.additionalProperties, indent + 1)};`,
    );
  } else if (s.additionalProperties === true) {
    lines.push(`${pad}[key: string]: unknown;`);
  }
  lines.push(`${close}}`);
  // For empty-ish objects with only index signature style maps used as Record
  if (
    Object.keys(props).length === 0 &&
    s.additionalProperties &&
    typeof s.additionalProperties === "object"
  ) {
    return `Record<string, ${tsTypeFromSchema(s.additionalProperties, indent)}>`;
  }
  return lines.join("\n");
}

function interfaceName(schema: JsonSchema, file: string): string {
  if (schema.title) return schema.title;
  return file.replace(/\.schema\.json$/, "").replace(/(^|-)(\w)/g, (_, _a, c) =>
    c.toUpperCase(),
  );
}

function main() {
  const schemas = loadSchemas();
  const hash = createHash("sha256");
  for (const s of schemas) {
    hash.update(s.name);
    hash.update("\0");
    hash.update(s.raw);
    hash.update("\0");
  }
  const sourceHash = hash.digest("hex");

  const chunks: string[] = [];
  chunks.push(`/* eslint-disable */`);
  chunks.push(`/**`);
  chunks.push(` * AUTO-GENERATED by scripts/generate-types.ts — DO NOT EDIT.`);
  chunks.push(` * Source: packages/protocol/schemas/*.schema.json`);
  chunks.push(` * Source SHA-256: ${sourceHash}`);
  chunks.push(` */`);
  chunks.push(``);
  chunks.push(`/** Exact protocol document version accepted by v0.1 schemas. */`);
  chunks.push(`export type ProtocolVersion = "0.1.0";`);
  chunks.push(``);
  chunks.push(`/** \`sha256:\` + 64 lowercase hex. */`);
  chunks.push(`export type Digest = string;`);
  chunks.push(``);
  chunks.push(`export type MeasurementValue = number | string | boolean;`);
  chunks.push(``);
  chunks.push(
    `export type MeasurementValueType = "number" | "boolean" | "string";`,
  );
  chunks.push(``);

  // Emit nested helper types from property shapes for readability
  // Prefer full interfaces from each schema file title.
  for (const { name, schema } of schemas) {
    const iface = interfaceName(schema, name);
    chunks.push(`export interface ${iface} ${tsTypeFromSchema(schema)}`);
    chunks.push(``);
  }

  // Aliases used by runtime code
  chunks.push(`export type SubjectType = EvidenceEnvelope["subject"]["type"];`);
  chunks.push(`export type Subject = EvidenceEnvelope["subject"];`);
  chunks.push(`export type Provenance = EvidenceEnvelope["provenance"];`);
  chunks.push(
    `export type ArtifactDescriptor = EvidenceEnvelope["artifacts"][number];`,
  );
  chunks.push(
    `export type ArtifactAvailability = ArtifactDescriptor["availability"];`,
  );
  chunks.push(
    `export type EvaluatorRef = BenchmarkManifest["evaluator"];`,
  );
  chunks.push(
    `export type EnvironmentSummary = NonNullable<BenchmarkManifest["environment"]>;`,
  );
  chunks.push(
    `export type DatasetPin = NonNullable<BenchmarkManifest["dataset"]>;`,
  );
  chunks.push(`export type VerifierRef = ArenaDefinition["verifier"];`);
  chunks.push(
    `export type TaskBinding = NonNullable<ArenaDefinition["taskBinding"]>;`,
  );
  chunks.push(
    `export type VerifierCapability = VerifierDescriptor["capabilities"][number];`,
  );
  chunks.push(
    `export type VerificationStatus = VerificationResult["status"];`,
  );
  chunks.push(``);

  const body = chunks.join("\n");
  writeFileSync(outFile, body.endsWith("\n") ? body : body + "\n", "utf8");
  console.log("wrote", outFile);
  console.log("sourceHash", sourceHash);
}

main();
